import type { TEnvelopeAiSummaryAttentionPoint } from '@documenso/lib/types/envelope-ai-summary';
import { cn } from '@documenso/ui/lib/utils';
import { Button } from '@documenso/ui/primitives/button';
import {
  Sheet,
  SheetContent,
  SheetDescription,
  SheetHeader,
  SheetTitle,
  SheetTrigger,
} from '@documenso/ui/primitives/sheet';
import { Skeleton } from '@documenso/ui/primitives/skeleton';
import { Trans } from '@lingui/react/macro';
import type { LucideIcon } from 'lucide-react';
import {
  AlertTriangleIcon,
  CalendarIcon,
  InfoIcon,
  ListChecksIcon,
  RefreshCwIcon,
  SparklesIcon,
  UsersIcon,
} from 'lucide-react';
import type { ReactNode } from 'react';
import { useRef, useState } from 'react';
import { match } from 'ts-pattern';

import {
  SummarizeDocumentError,
  summarizeDocument,
  type TSummarizeDocumentResponse,
} from '../../../../server/api/ai/summarize-document.client';
import { useRequiredEnvelopeSigningContext } from '../document-signing/envelope-signing-provider';

export type EnvelopeSigningAiSummarySheetProps = {
  trigger: ReactNode;
};

type SummaryState =
  | { status: 'idle' }
  | { status: 'loading' }
  | { status: 'success'; data: TSummarizeDocumentResponse }
  | { status: 'error'; message: string; isRateLimited: boolean };

export const EnvelopeSigningAiSummarySheet = ({ trigger }: EnvelopeSigningAiSummarySheetProps) => {
  const { recipient, envelope } = useRequiredEnvelopeSigningContext();

  const [isOpen, setIsOpen] = useState(false);
  const [state, setState] = useState<SummaryState>({ status: 'idle' });

  const abortControllerRef = useRef<AbortController | null>(null);

  const loadSummary = async () => {
    abortControllerRef.current?.abort();

    const abortController = new AbortController();
    abortControllerRef.current = abortController;

    setState({ status: 'loading' });

    try {
      const data = await summarizeDocument({ token: recipient.token }, abortController.signal);

      setState({ status: 'success', data });
    } catch (err) {
      if (abortController.signal.aborted) {
        return;
      }

      const error = err instanceof SummarizeDocumentError ? err : null;

      setState({
        status: 'error',
        message: error?.message ?? '',
        isRateLimited: error?.status === 429,
      });
    }
  };

  const onOpenChange = (open: boolean) => {
    setIsOpen(open);

    // Only fetch once per page view; the server caches summaries per document anyway.
    if (open && (state.status === 'idle' || state.status === 'error')) {
      void loadSummary();
    }

    if (!open && state.status === 'loading') {
      abortControllerRef.current?.abort();
      setState({ status: 'idle' });
    }
  };

  return (
    <Sheet open={isOpen} onOpenChange={onOpenChange}>
      <SheetTrigger asChild>{trigger}</SheetTrigger>

      <SheetContent position="right" size="content" className="flex w-full max-w-lg flex-col gap-0 p-0">
        <SheetHeader className="space-y-1 border-border border-b px-6 py-5 text-left">
          <SheetTitle className="flex items-center gap-2">
            <SparklesIcon className="size-4 text-auth-accent" aria-hidden />
            <Trans>Document summary</Trans>
          </SheetTitle>

          <SheetDescription className="truncate" title={envelope.title}>
            {envelope.title}
          </SheetDescription>
        </SheetHeader>

        <div className="flex-1 overflow-y-auto px-6 py-5">
          {match(state)
            .with({ status: 'idle' }, { status: 'loading' }, () => <SummaryLoadingState />)
            .with({ status: 'error' }, ({ message, isRateLimited }) => (
              <SummaryErrorState message={message} isRateLimited={isRateLimited} onRetry={loadSummary} />
            ))
            .with({ status: 'success' }, ({ data }) => <SummaryContent data={data} />)
            .exhaustive()}
        </div>

        <p className="border-border border-t bg-muted/40 px-6 py-4 text-muted-foreground text-xs">
          <Trans>
            This summary was generated by AI and may be incomplete or wrong. It is not legal advice. Always read the
            full document before you sign.
          </Trans>
        </p>
      </SheetContent>
    </Sheet>
  );
};

const SummaryContent = ({ data }: { data: TSummarizeDocumentResponse }) => {
  const { summary } = data;

  return (
    <div className="flex flex-col gap-6">
      <section className="flex flex-col gap-2">
        <span className="w-fit rounded-full bg-auth-band px-2.5 py-0.5 font-medium text-auth-accent text-xs">
          {summary.documentType}
        </span>

        <p className="text-foreground text-sm leading-relaxed">{summary.overview}</p>
      </section>

      {summary.attentionPoints.length > 0 && (
        <SummarySection icon={AlertTriangleIcon} title={<Trans>Read carefully</Trans>}>
          <ul className="flex flex-col gap-2">
            {summary.attentionPoints.map((point, index) => (
              <AttentionPoint key={index} point={point} />
            ))}
          </ul>
        </SummarySection>
      )}

      {summary.keyPoints.length > 0 && (
        <SummarySection icon={ListChecksIcon} title={<Trans>Key points</Trans>}>
          <ul className="flex flex-col gap-3">
            {summary.keyPoints.map((point, index) => (
              <li key={index} className="flex flex-col gap-0.5">
                <span className="font-medium text-foreground text-sm">{point.title}</span>
                <span className="text-muted-foreground text-sm">{point.detail}</span>
              </li>
            ))}
          </ul>
        </SummarySection>
      )}

      {summary.importantDates.length > 0 && (
        <SummarySection icon={CalendarIcon} title={<Trans>Dates and deadlines</Trans>}>
          <dl className="divide-y divide-border rounded-md border border-border">
            {summary.importantDates.map((date, index) => (
              <div key={index} className="flex items-start justify-between gap-4 px-3 py-2 text-sm">
                <dt className="text-muted-foreground">{date.label}</dt>
                <dd className="text-right font-medium text-foreground">{date.value}</dd>
              </div>
            ))}
          </dl>
        </SummarySection>
      )}

      {summary.parties.length > 0 && (
        <SummarySection icon={UsersIcon} title={<Trans>Parties</Trans>}>
          <ul className="flex flex-col gap-1.5">
            {summary.parties.map((party, index) => (
              <li key={index} className="flex items-baseline justify-between gap-4 text-sm">
                <span className="font-medium text-foreground">{party.name}</span>
                <span className="text-right text-muted-foreground">{party.role}</span>
              </li>
            ))}
          </ul>
        </SummarySection>
      )}
    </div>
  );
};

const SummarySection = ({
  icon: Icon,
  title,
  children,
}: {
  icon: LucideIcon;
  title: ReactNode;
  children: ReactNode;
}) => {
  return (
    <section className="flex flex-col gap-3">
      <h3 className="flex items-center gap-2 font-semibold text-foreground text-sm">
        <Icon className="size-4 text-muted-foreground" aria-hidden />
        {title}
      </h3>
      {children}
    </section>
  );
};

const AttentionPoint = ({ point }: { point: TEnvelopeAiSummaryAttentionPoint }) => {
  const Icon = point.severity === 'info' ? InfoIcon : AlertTriangleIcon;

  return (
    <li
      className={cn('flex gap-3 rounded-md border p-3', {
        'border-border bg-muted/40': point.severity === 'info',
        'border-warning/40 bg-warning/10': point.severity === 'caution',
        'border-destructive-border bg-destructive-subtle': point.severity === 'warning',
      })}
    >
      <Icon
        aria-hidden
        className={cn('mt-0.5 size-4 shrink-0', {
          'text-muted-foreground': point.severity === 'info',
          'text-warning': point.severity === 'caution',
          'text-destructive': point.severity === 'warning',
        })}
      />

      <div className="flex flex-col gap-0.5">
        <span className="font-medium text-foreground text-sm">{point.title}</span>
        <span className="text-muted-foreground text-sm">{point.detail}</span>
      </div>
    </li>
  );
};

const SummaryLoadingState = () => {
  return (
    <div className="flex flex-col gap-6" aria-busy>
      <p className="flex items-center gap-2 text-muted-foreground text-sm">
        <SparklesIcon className="size-4 animate-pulse text-auth-accent" aria-hidden />
        <Trans>Reading the document. This can take up to 30 seconds.</Trans>
      </p>

      <div className="flex flex-col gap-2">
        <Skeleton className="h-5 w-32 rounded-full" />
        <Skeleton className="h-4 w-full rounded-full" />
        <Skeleton className="h-4 w-11/12 rounded-full" />
        <Skeleton className="h-4 w-4/5 rounded-full" />
      </div>

      <div className="flex flex-col gap-2">
        <Skeleton className="h-4 w-28 rounded-full" />
        <Skeleton className="h-16 w-full rounded-md" />
        <Skeleton className="h-16 w-full rounded-md" />
      </div>
    </div>
  );
};

type SummaryErrorStateProps = {
  message: string;
  isRateLimited: boolean;
  onRetry: () => void;
};

const SummaryErrorState = ({ message, isRateLimited, onRetry }: SummaryErrorStateProps) => {
  return (
    <div className="flex flex-col items-start gap-3 rounded-md border border-destructive-border bg-destructive-subtle p-4">
      <p className="font-medium text-destructive text-sm">
        {isRateLimited ? (
          <Trans>Too many summary requests. Please wait a minute and try again.</Trans>
        ) : (
          <Trans>We couldn't summarise this document.</Trans>
        )}
      </p>

      {!isRateLimited && message && <p className="text-muted-foreground text-sm">{message}</p>}

      <Button type="button" variant="outline" size="sm" className="bg-card" onClick={onRetry}>
        <RefreshCwIcon className="mr-2 size-4" aria-hidden />
        <Trans>Try again</Trans>
      </Button>
    </div>
  );
};
